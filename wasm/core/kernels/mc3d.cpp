inline double clampRange(double v) {
    if (v < -1e6) return -1e6;
    if (v > 1e6) return 1e6;
    return v;
}

// Identical to the page's inline getOffset()/getOffset2D() closures.
inline double edgeOffset(double v1, double v2) {
    const double delta = v2 - v1;
    if (std::fabs(delta) < 1e-9) return 0.5;
    double t = (0.0 - v1) / delta;
    if (t < 0.0) t = 0.0;
    else if (t > 1.0) t = 1.0;
    return t;
}

