// ArchCore kernel "mc3d": marching-cubes mesh generation for recalculate3D()'s
// two volumetric blocks -- the true implicit3d surface (plotType==='implicit3d')
// and the implicit-curve-extruded-to-3D "wall" (is2D && entry.extendTo3D &&
// plotType==='implicit'). Both blocks in the page share the same classic
// Paul-Bourke marching-cubes cell/triangle logic (same edgeTable/triTable,
// same getOffset), differing only in how the scalar field is sampled (a true
// 3D grid vs. a 2D field copied across z-layers) and in the gradient/normal
// formula (3D central difference vs. a 2D-only one with dz forced to 0).
//
// Exactness notes (see KERNEL_GUIDE.md):
//  - The value grid is stored as float (the JS side stores it in a
//    Float32Array), so corner values used for cube classification / edge
//    interpolation carry the JS's float32 rounding; gradient sample values
//    come straight from Program::evaluate() (double), matching the JS local
//    variables (never round-tripped through a typed array).
//  - Number.isFinite(val) is false for both NaN and +-Infinity, so only
//    finite values get clamped to [-1e6,1e6]; non-finite ones become NaN.
//  - The cell-skip test only ever inspects corner 0 (values[idx]) for NaN,
//    exactly like the page.
//  - No vertex/gradient dedup across shared edges (matches the page); this
//    kernel batches the *evaluate calls* only, which does not change any
//    output value since Program::evaluate is a pure per-lane function.

